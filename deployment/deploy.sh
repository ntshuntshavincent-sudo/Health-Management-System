#!/bin/bash
# ─────────────────────────────────────────────────────────────────────────────
# PATIENT SYSTEM — FULL DEPLOYMENT SCRIPT
# Ubuntu 22.04 LTS server (e.g. a clinic PC running Ubuntu, or a VPS)
#
# RUN ONCE on a fresh server:
#   chmod +x deploy.sh
#   sudo ./deploy.sh
#
# This script installs and configures everything from scratch:
#   Node.js 20, PostgreSQL 15, Nginx, PM2, SSL certificates
# ─────────────────────────────────────────────────────────────────────────────

set -e  # Stop on any error

# ── Config — EDIT THESE BEFORE RUNNING ───────────────────────────────────────
DOMAIN="yourhospital.co.za"          # Your actual domain name
DB_NAME="patient_system"
DB_USER="patient_app"
DB_PASS="$(openssl rand -base64 32)" # Strong random password — will be shown at end
APP_DIR="/var/www/patient-system"
EMAIL="admin@yourhospital.co.za"     # For SSL certificate notifications

echo ""
echo "═══════════════════════════════════════════════"
echo "  Patient System — Deployment Script"
echo "═══════════════════════════════════════════════"
echo ""

# ── 1. System update ──────────────────────────────────────────────────────────
echo "▶ Step 1/9: Updating system packages..."
apt update -y && apt upgrade -y
apt install -y curl wget git ufw fail2ban

# ── 2. Firewall ───────────────────────────────────────────────────────────────
echo "▶ Step 2/9: Configuring firewall..."
ufw default deny incoming
ufw default allow outgoing
ufw allow ssh
ufw allow 'Nginx Full'    # Opens ports 80 (HTTP) and 443 (HTTPS)
ufw --force enable
echo "  Firewall: SSH + HTTP + HTTPS allowed. Everything else blocked."

# ── 3. Node.js 20 ─────────────────────────────────────────────────────────────
echo "▶ Step 3/9: Installing Node.js 20..."
curl -fsSL https://deb.nodesource.com/setup_20.x | bash -
apt install -y nodejs
node --version
npm --version

# Install PM2 globally to keep Node.js running
npm install -g pm2

# ── 4. PostgreSQL ─────────────────────────────────────────────────────────────
echo "▶ Step 4/9: Installing and configuring PostgreSQL..."
apt install -y postgresql postgresql-contrib

# Start and enable PostgreSQL
systemctl enable postgresql
systemctl start postgresql

# Create the app database and user
sudo -u postgres psql << SQL
  -- Create a dedicated database user (NOT the postgres superuser)
  CREATE USER ${DB_USER} WITH ENCRYPTED PASSWORD '${DB_PASS}';

  -- Create the database
  CREATE DATABASE ${DB_NAME} OWNER ${DB_USER};

  -- Grant only what the app needs — principle of least privilege
  GRANT CONNECT ON DATABASE ${DB_NAME} TO ${DB_USER};
SQL

echo "  PostgreSQL: database '${DB_NAME}' and user '${DB_USER}' created."

# ── 5. Clone / copy app ───────────────────────────────────────────────────────
echo "▶ Step 5/9: Setting up application directory..."
mkdir -p ${APP_DIR}/backend
mkdir -p ${APP_DIR}/frontend
mkdir -p ${APP_DIR}/backend/logs

# If deploying from Git:
# git clone https://github.com/yourusername/patient-system.git ${APP_DIR}/backend
# For now, we assume files are already copied to the server

echo "  App directory created: ${APP_DIR}"

# ── 6. Environment file ───────────────────────────────────────────────────────
echo "▶ Step 6/9: Creating .env file..."
JWT_SECRET=$(openssl rand -base64 64 | tr -d '\n')

cat > ${APP_DIR}/backend/.env << ENV
# Auto-generated by deploy.sh on $(date)
NODE_ENV=production
PORT=3000

DB_HOST=localhost
DB_PORT=5432
DB_NAME=${DB_NAME}
DB_USER=${DB_USER}
DB_PASSWORD=${DB_PASS}

JWT_SECRET=${JWT_SECRET}

FRONTEND_URL=https://${DOMAIN}
ENV

chmod 600 ${APP_DIR}/backend/.env  # Only root can read this file
echo "  .env file created and locked (chmod 600)."

# ── 7. Install npm dependencies & run DB migration ───────────────────────────
echo "▶ Step 7/9: Installing Node.js dependencies..."
cd ${APP_DIR}/backend
npm install --omit=dev   # Production dependencies only

echo "  Running database migration..."
PGPASSWORD=${DB_PASS} psql -h localhost -U ${DB_USER} -d ${DB_NAME} -f db/migrate.sql
echo "  Database tables created."

# ── 8. Nginx ──────────────────────────────────────────────────────────────────
echo "▶ Step 8/9: Configuring Nginx..."
apt install -y nginx certbot python3-certbot-nginx

# Copy Nginx config
cp ${APP_DIR}/backend/nginx.conf /etc/nginx/sites-available/patient-system

# Replace placeholder domain with actual domain
sed -i "s/yourhospital.co.za/${DOMAIN}/g" /etc/nginx/sites-available/patient-system

# Enable the site
ln -sf /etc/nginx/sites-available/patient-system /etc/nginx/sites-enabled/
rm -f /etc/nginx/sites-enabled/default  # Remove default Nginx page

nginx -t  # Test config
systemctl enable nginx
systemctl restart nginx

# Get SSL certificate from Let's Encrypt (FREE)
echo "  Obtaining SSL certificate from Let's Encrypt..."
certbot --nginx -d ${DOMAIN} -d www.${DOMAIN} \
  --non-interactive --agree-tos --email ${EMAIL} \
  --redirect  # Auto-redirects HTTP to HTTPS

echo "  SSL certificate installed. Auto-renewal is active."

# ── 9. Start app with PM2 ─────────────────────────────────────────────────────
echo "▶ Step 9/9: Starting application with PM2..."
cd ${APP_DIR}/backend
pm2 start ecosystem.config.js --env production
pm2 save            # Save process list
pm2 startup systemd # Enable on boot
# Run the command PM2 prints to complete startup config

echo ""
echo "═══════════════════════════════════════════════"
echo "  DEPLOYMENT COMPLETE"
echo "═══════════════════════════════════════════════"
echo ""
echo "  Your system is live at: https://${DOMAIN}"
echo "  Health check:           https://${DOMAIN}/health"
echo ""
echo "  IMPORTANT — save these credentials securely:"
echo "  ─────────────────────────────────────────────"
echo "  Database user:     ${DB_USER}"
echo "  Database password: ${DB_PASS}"
echo "  (also saved in ${APP_DIR}/backend/.env)"
echo ""
echo "  Useful commands:"
echo "    pm2 status                → check if app is running"
echo "    pm2 logs patient-system   → view live logs"
echo "    pm2 restart patient-system → restart after updates"
echo "    nginx -t                  → test nginx config"
echo "    certbot renew --dry-run   → test SSL renewal"
echo ""
